/**
 * Approved public photographers, optionally narrowed by specialisation and/or
 * city (city/working-region match), loosening the filters when nothing
 * matches so the section is never empty for a thin marketplace.
 */
function find_photographers($db, $specialty = null, $city = null, $limit = 3, &$matchLevel = null)
{
    $matchLevel = null;
    try {
        $all = $db->select('freelancer_applications', [
            'status' => 'approved',
            'is_public' => true,
            'order' => 'rating_avg DESC, created_at DESC',
            'limit' => 200,
        ]);
    } catch (Exception $e) {
        error_log('find_photographers failed (migrations pending?): ' . $e->getMessage());
        return [];
    }
    $matchesCity = function ($p) use ($city) {
        if (!$city) {
            return true;
        }
        if (mb_stripos($p['city'] ?? '', $city) !== false) {
            return true;
        }
        foreach (json_decode($p['working_regions'] ?? '[]', true) ?: [] as $region) {
            if (isset($region['province_name']) && mb_stripos($region['province_name'], $city) !== false) {
                return true;
            }
        }
        return false;
    };
    $matchesSpec = function ($p) use ($specialty) {
        return !$specialty || in_array($specialty, json_decode($p['specialization'] ?? '[]', true) ?: [], true);
    };
    // $matchLevel: 'both', 'city', 'specialty' or 'any' - lets the caller word the heading honestly.
    foreach (['both' => [$matchesCity, $matchesSpec], 'city' => [$matchesCity], 'specialty' => [$matchesSpec], 'any' => []] as $level => $filters) {
        $found = array_values(array_filter($all, function ($p) use ($filters) {
            foreach ($filters as $filter) {
                if (!$filter($p)) {
                    return false;
                }
            }
            return true;
        }));
        if ($found) {
            $matchLevel = $level;
            return array_slice($found, 0, $limit);
        }
    }
    return [];
}

/**
 * Published services, one per title. The posts table holds some services twice
 * (a legacy "mimari-fotografcilik" row next to "hizmetlerimiz/mimari-fotografcilik");
 * the row with the full page body wins, and the short legacy row's one-line
 * body fills in its missing excerpt.
 */
function published_services($db)
{
    $rows = $db->select('posts', [
        'post_type' => 'service',
        'post_status' => 'publish',
        'limit' => 100,
        'order' => 'title ASC'
    ]);
    $byTitle = [];
    foreach ($rows as $row) {
        $key = mb_strtolower(trim($row['title']));
        $current = $byTitle[$key] ?? null;
        if (!$current) {
            $byTitle[$key] = $row;
            continue;
        }
        [$long, $short] = strlen($row['content'] ?? '') > strlen($current['content'] ?? '') ? [$row, $current] : [$current, $row];
        // The legacy duplicate's body is a one-line summary: reuse it as the excerpt.
        if (empty($long['excerpt']) && ($short['content'] ?? '') !== '' && strpos($short['content'], '<') === false) {
            $long['excerpt'] = trim($short['content']);
        }
        $byTitle[$key] = $long;
    }
    return array_values($byTitle);
}
