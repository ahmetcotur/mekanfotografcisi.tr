/**
 * Cache-busted URL for a file under the web root. Uses the file's mtime, so
 * browsers can cache assets and still pick up new deploys.
 */
function asset_url($path)
{
    $path = '/' . ltrim($path, '/');
    $file = dirname(__DIR__) . $path;
    $version = is_file($file) ? filemtime($file) : '1';
    return $path . '?v=' . $version;
}

/**
 * Parse "#rgb" / "#rrggbb" into [r, g, b], or null when invalid.
 */
function hex_to_rgb($hex)
{
    $hex = ltrim(trim((string) $hex), '#');
    if (strlen($hex) === 3) {
        $hex = $hex[0] . $hex[0] . $hex[1] . $hex[1] . $hex[2] . $hex[2];
    }
    if (!preg_match('/^[0-9a-fA-F]{6}$/', $hex)) {
        return null;
    }
    return [hexdec(substr($hex, 0, 2)), hexdec(substr($hex, 2, 2)), hexdec(substr($hex, 4, 2))];
}

/**
 * The accent colour used across the public site. This is the colour that
 * already drove every button before the redesign (`secondary_color`, which
 * the old header mapped to brand-600), falling back to the default orange.
 */
function brand_accent_hex()
{
    foreach (['accent_color', 'secondary_color'] as $key) {
        $value = get_setting($key);
        if ($value && hex_to_rgb($value)) {
            return $value;
        }
    }
    return '#dc6809';
}

/**
 * CSS custom properties for the brand scale (50-950), generated by mixing the
 * accent colour with white (lighter shades) and black (darker shades). Values
 * are bare "r g b" channels so Tailwind's opacity modifiers keep working.
 */
function brand_palette_css()
{
    $rgb = hex_to_rgb(brand_accent_hex()) ?: [220, 104, 9];
    $mix = [
        50 => ['w', 0.95], 100 => ['w', 0.88], 200 => ['w', 0.75], 300 => ['w', 0.55], 400 => ['w', 0.30],
        500 => ['w', 0.0],
        600 => ['b', 0.15], 700 => ['b', 0.32], 800 => ['b', 0.48], 900 => ['b', 0.62], 950 => ['b', 0.75],
    ];
    $vars = [];
    foreach ($mix as $shade => [$towards, $amount]) {
        $channels = array_map(function ($c) use ($towards, $amount) {
            return (int) round($towards === 'w' ? $c + (255 - $c) * $amount : $c * (1 - $amount));
        }, $rgb);
        $vars[] = "--brand-{$shade}: " . implode(' ', $channels) . ';';
    }
    return ':root{' . implode('', $vars) . '}';
}

/**
 * True when the current request path is $path (or below it, with $prefix).
 */
function is_current_path($path, $prefix = false)
{
    $current = '/' . trim(parse_url($_SERVER['REQUEST_URI'] ?? '/', PHP_URL_PATH) ?: '/', '/');
    $path = '/' . trim($path, '/');
    if ($current === $path) {
        return true;
    }
    return $prefix && $path !== '/' && strpos($current, $path . '/') === 0;
}

