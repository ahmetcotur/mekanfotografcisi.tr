/**
 * Photo URL from a Pexels/media row whose 'src' may be a string or a size map.
 */
function photo_src($photo, $size = 'large')
{
    if (!$photo) {
        return '';
    }
    $src = $photo['src'] ?? '';
    if (is_array($src)) {
        return $src[$size] ?? $src['large'] ?? $src['original'] ?? '';
    }
    return (string) $src;
}

/**
 * Normalised WhatsApp link from the admin setting, or '' when unset.
 */
function whatsapp_url($text = '')
{
    $number = preg_replace('/\D+/', '', (string) get_setting('whatsapp_number'));
    if ($number === '') {
        return '';
    }
    return 'https://wa.me/' . $number . ($text !== '' ? '?text=' . rawurlencode($text) : '');
}

/**
 * tel: href from the phone setting.
 */
function phone_href()
{
    $phone = get_setting('phone_url') ?: get_setting('phone');
    $digits = preg_replace('/[^\d+]/', '', (string) $phone);
    return $digits !== '' ? 'tel:' . $digits : '';
}

