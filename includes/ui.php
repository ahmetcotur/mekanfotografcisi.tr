/**
 * Minimal Markdown -> HTML for the generated location pages (headings, lists,
 * bold/italic, paragraphs). Text is escaped first.
 */
function simple_markdown($markdown)
{
    $lines = preg_split('/\R/', trim((string) $markdown));
    $html = '';
    $paragraph = [];
    $list = null;
    $inline = function ($text) {
        $text = e($text);
        $text = preg_replace('/\*\*(.+?)\*\*/', '<strong>$1</strong>', $text);
        return preg_replace('/(?<!\*)\*(?!\s)(.+?)\*/', '<em>$1</em>', $text);
    };
    $flush = function () use (&$html, &$paragraph, &$list, $inline) {
        if ($paragraph) {
            $html .= '<p>' . $inline(implode(' ', $paragraph)) . '</p>';
            $paragraph = [];
        }
        if ($list) {
            $html .= '<' . $list['tag'] . '>' . implode('', array_map(function ($item) use ($inline) {
                return '<li>' . $inline($item) . '</li>';
            }, $list['items'])) . '</' . $list['tag'] . '>';
            $list = null;
        }
    };
    foreach ($lines as $line) {
        $line = trim($line);
        if ($line === '') {
            $flush();
        } elseif (preg_match('/^(#{1,4})\s+(.+)$/', $line, $m)) {
            $flush();
            // A page has one <h1> (the hero), so markdown headings start at h2.
            $level = min(4, strlen($m[1]) + 1);
            $html .= "<h{$level}>" . $inline($m[2]) . "</h{$level}>";
        } elseif (preg_match('/^(?:[-*]|(\d+)\.)\s+(.+)$/', $line, $m)) {
            if ($paragraph) {
                $html .= '<p>' . $inline(implode(' ', $paragraph)) . '</p>';
                $paragraph = [];
            }
            $tag = $m[1] !== '' ? 'ol' : 'ul';
            if ($list && $list['tag'] !== $tag) {
                $flush();
            }
            $list = $list ?: ['tag' => $tag, 'items' => []];
            $list['items'][] = $m[2];
        } else {
            if ($list) {
                $flush();
            }
            $paragraph[] = $line;
        }
    }
    $flush();
    return $html;
}

/**
 * Prepare a stored page body for rendering inside the new page layout:
 * Markdown bodies are converted; HTML bodies lose the page header / outer
 * padding they carried from the old full-page layout, and any <h1> is demoted
 * (the page hero already renders the title as the one <h1>).
 */
function prepare_page_content($content, $title = '')
{
    $content = trim((string) $content);
    if ($content === '') {
        return '';
    }
    if ($content[0] !== '<') {
        // Drop a leading "# Title" that just repeats the page title.
        $content = preg_replace('/^#\s+.+\R+/', '', $content, 1);
        return simple_markdown($content);
    }
    // Drop a leading <h1> that just repeats the page title.
    if ($title !== '' && preg_match('#<h1[^>]*>(.*?)</h1>#s', $content, $m)
        && mb_strtolower(trim(strip_tags($m[1]))) === mb_strtolower(trim($title))) {
        $content = str_replace($m[0], '', $content);
    }
    $content = preg_replace('#<!--\s*Header\s*-->\s*<div[^>]*>\s*(?:<span[^>]*>.*?</span>)?\s*<h1[^>]*>.*?</h1>\s*(?:<div[^>]*>\s*</div>)?\s*</div>#s', '', $content, 1);
    $content = str_replace(['class="pt-32 pb-20"', 'class="container mx-auto px-4"'], ['class=""', 'class=""'], $content);
    return preg_replace('#<(/?)h1\b#i', '<$1h2', $content);
}

/**
 * Plain-text summary of a page body, used when a post has no excerpt.
 */
function content_excerpt($content, $length = 160)
{
    $html = trim((string) $content);
    if ($html !== '' && $html[0] !== '<') {
        $html = simple_markdown(preg_replace('/^#\s+.+\R+/', '', $html, 1));
    }
    if (preg_match_all('#<p[^>]*>(.*?)</p>#s', $html, $m)) {
        foreach ($m[1] as $p) {
            $text = trim(preg_replace('/\s+/', ' ', html_entity_decode(strip_tags($p), ENT_QUOTES, 'UTF-8')));
            if (mb_strlen($text) > 40) {
                return mb_strlen($text) > $length ? rtrim(mb_substr($text, 0, $length - 1)) . '…' : $text;
            }
        }
    }
    return '';
}

